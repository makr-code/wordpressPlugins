from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parents[1]
CACHE_PATH = ROOT / "output" / "docs_cache.json"
PLAN_PATH = ROOT / "output" / "docs_sync_plan.json"


def load_json(path: Path) -> Dict[str, Any]:
    if not path.exists():
        return {"documents": []}
    return json.loads(path.read_text(encoding="utf-8"))


def compare_docs(current: Dict[str, Any], previous: Dict[str, Any]) -> Dict[str, Any]:
    prev_map = {item["slug"]: item for item in previous.get("documents", [])}
    current_map = {item["slug"]: item for item in current.get("documents", [])}

    new_items = []
    updated_items = []
    unchanged_items = []
    deleted_items = []

    for slug, item in current_map.items():
        prev = prev_map.get(slug)
        if prev is None:
            new_items.append(item)
        elif prev.get("hash") != item.get("hash"):
            updated_items.append({"previous": prev, "current": item})
        else:
            unchanged_items.append(item)

    for slug, item in prev_map.items():
        if slug not in current_map:
            deleted_items.append(item)

    return {
        "summary": {
            "new": len(new_items),
            "updated": len(updated_items),
            "unchanged": len(unchanged_items),
            "deleted": len(deleted_items),
        },
        "new": new_items,
        "updated": updated_items,
        "unchanged": unchanged_items,
        "deleted": deleted_items,
    }


def write_plan(plan: Dict[str, Any], output_path: Path = PLAN_PATH) -> Path:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(plan, ensure_ascii=False, indent=2), encoding="utf-8")
    return output_path


def sync_documents(manifest_path: Path = CACHE_PATH, apply: bool = False) -> Dict[str, Any]:
    current = load_json(manifest_path)
    previous = load_json(ROOT / "output" / "docs_cache_previous.json")
    plan = compare_docs(current, previous)

    plan["generated_at"] = datetime.now(timezone.utc).isoformat()
    plan["manifest_path"] = str(manifest_path)

    if apply:
        previous_path = ROOT / "output" / "docs_cache_previous.json"
        previous_path.write_text(json.dumps(current, ensure_ascii=False, indent=2), encoding="utf-8")
        write_plan(plan, PLAN_PATH)
        print(f"[docs-sync] update cache: {previous_path}")
        print(f"[docs-sync] wrote plan: {PLAN_PATH}")

    return plan


def main() -> None:
    parser = argparse.ArgumentParser(description="Compare the current docs cache with the previous state to compute CRUD changes")
    parser.add_argument("--manifest", default=str(CACHE_PATH), help="JSON manifest generated by docs_manifest.py")
    parser.add_argument("--apply", action="store_true", help="Persist the previous-state cache and write the sync plan")
    parser.add_argument("--json", action="store_true", help="Print the plan as JSON")
    args = parser.parse_args()

    manifest_path = Path(args.manifest).resolve()
    plan = sync_documents(manifest_path, apply=args.apply)

    if args.json:
        payload = json.dumps(plan, ensure_ascii=False, indent=2)
        import sys
        sys.stdout.reconfigure(encoding='utf-8')
        print(payload)
        return

    print("[docs-sync] summary:")
    summary = plan["summary"]
    print(f"  new={summary['new']} updated={summary['updated']} unchanged={summary['unchanged']} deleted={summary['deleted']}")
    if plan["new"]:
        print("  new files:")
        for item in plan["new"][:5]:
            print(f"    - {item['slug']} ({item['relative_path']})")
    if plan["updated"]:
        print("  changed files:")
        for item in plan["updated"][:5]:
            print(f"    - {item['current']['slug']} ({item['current']['relative_path']})")
    if plan["deleted"]:
        print("  deleted files:")
        for item in plan["deleted"][:5]:
            print(f"    - {item['slug']} ({item['relative_path']})")


if __name__ == "__main__":
    main()
